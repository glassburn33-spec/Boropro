export const getTorchsByBrand = (brand: string): TorchSpec[] => {
  return torchDatabase.filter((torch) => torch.brand === brand);
};

export const getTorchsByType = (type: string): TorchSpec[] => {
  return torchDatabase.filter((torch) => torch.type === type);
};

export const getTorchsByCapacity = (capacity: string): TorchSpec[] => {
  const capacityMap: { [key: string]: number } = {
    '1"': 1,
    '1.5"': 1.5,
    '2"': 2,
    '2.5"': 2.5,
    '3"': 3,
    '3.5"': 3.5,
    '4"': 4,
  };

  const minCapacity = capacityMap[capacity] || 0;

  return torchDatabase.filter((torch) => {
    const boroMax = parseFloat(torch.boroCapacity);
    return boroMax >= minCapacity;
  });
};
